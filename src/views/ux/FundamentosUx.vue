    <h2>Carga cognitiva</h2>
    <p>
      La carga cognitiva aumenta con el exceso de opciones, el lenguaje técnico, los pasos
      ocultos, los errores poco claros y los diseños incoherentes. Para reducirla conviene:
    </p>
    <ul>
      <li>dividir los procesos largos en pasos y mostrar el progreso;</li>
      <li>agrupar la información relacionada;</li>
      <li>usar valores por defecto razonables;</li>
      <li>no pedir datos que ya se conocen;</li>
      <li>confirmar las acciones críticas;</li>
      <li>mantener consistencia visual y terminológica.</li>
    </ul>
    <p>
      Varias de las «Leyes UX» recogidas en este bloque explican por qué funcionan estas medidas
      (por ejemplo, la ley de Miller sobre el número de elementos que podemos retener, o la ley de
      Hick sobre el tiempo que se tarda en decidir entre muchas opciones); pueden consultarse en el
      apartado «Leyes UX: carga mental y decisión».
    </p>

    <h2>Accesibilidad cognitiva</h2>
    <p>
      La accesibilidad cognitiva facilita comprender, aprender, recordar, orientarse y decidir.
      Beneficia, entre otras, a personas con:
    </p>
    <ul>
      <li>discapacidad intelectual,</li>
      <li>trastornos de atención,</li>
      <li>dislexia,</li>
      <li>daño cerebral,</li>
      <li>bajo dominio del idioma,</li>
      <li>estrés,</li>
      <li>poca experiencia digital.</li>
    </ul>
    <p>Medidas concretas para mejorarla:</p>
    <ul>
      <li>lenguaje claro,</li>
      <li>estructura visual simple,</li>
      <li>instrucciones antes del formulario,</li>
      <li>ejemplos,</li>
      <li>prevención de errores,</li>
      <li>tiempo suficiente para completar tareas,</li>
      <li>ayuda contextual,</li>
      <li>evitar animaciones o distracciones innecesarias.</li>
    </ul>
    <p>Dos de ellas tienen respaldo directo en las WCAG:</p>
