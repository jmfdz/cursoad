    <h2>Directiva (UE) 2019/882 y Ley 11/2023</h2>
    <p>
      Durante años la obligación legal se ceñía al sector público, y esa es la idea que todavía
      arrastra mucha gente. Ya no es así: la Directiva (UE) 2019/882, conocida como
      <strong>Acta Europea de Accesibilidad</strong>, extiende los requisitos a determinados
      productos y servicios del <strong>sector privado</strong>. En España se traspuso mediante la
      <strong>Ley 11/2023, de 8 de mayo</strong>, y es aplicable desde el
      <strong>28 de junio de 2025</strong>.
    </p>
    <p>Entre los servicios afectados están, con matices y excepciones según el caso:</p>
    <ul>
      <li>el comercio electrónico,</li>
      <li>los servicios bancarios para consumidores,</li>
      <li>los libros electrónicos y su software de lectura,</li>
      <li>los servicios de comunicaciones electrónicas,</li>
      <li>los servicios de transporte de viajeros y sus webs y aplicaciones,</li>
      <li>y el acceso a servicios de comunicación audiovisual.</li>
    </ul>
    <p>
      La norma contempla exenciones, entre ellas la de las microempresas que prestan servicios, y
      la posibilidad de alegar carga desproporcionada con la misma exigencia de motivación que en el
      caso anterior.
    </p>
    <p>
      La consecuencia práctica para quien desarrolla es sencilla de resumir: el criterio técnico ya
      no cambia según quién sea el cliente. Un mismo desarrollo hecho para una universidad o para
      una empresa privada de comercio electrónico se enfrenta hoy a requisitos equivalentes.
    </p>

    <h2>Norma europea EN 301 549</h2>
    <p>
      El estándar técnico europeo de referencia es la EN 301 549, que recoge requisitos de
      accesibilidad para productos y servicios TIC.
    </p>
    <p>
      Conviene matizar algo: la versión armonizada vigente de EN 301 549 utilizada en este
      contexto europeo sigue apoyándose en <strong>WCAG 2.1</strong> para web, documentos y
      aplicaciones. Aun así, desde el punto de vista técnico tiene sentido trabajar ya con
      <strong>WCAG 2.2</strong> como referencia de mejora, porque amplía criterios y no contradice
      lo anterior.
    </p>
    <p>
      Además, EN 301 549 no se limita a páginas web. También cubre otros entornos, productos y
      servicios digitales, por lo que actúa como un marco más amplio cuando hablamos de
      accesibilidad en TIC.
    </p>

    <h2>Qué implica en la práctica</h2>
    <p>
      Sea cual sea la norma que aplique, en la práctica cumplirla no consiste solo en pasar un
      validador. Implica diseñar,
      desarrollar, mantener y revisar los contenidos con criterios de accesibilidad, documentar el
      estado real del servicio y ofrecer vías para que una persona usuaria pueda comunicar barreras,
      solicitar alternativas o ejercer sus derechos.
    </p>
    <p>
      Por eso conviene leer la legislación junto con las WCAG: la legislación marca el marco de
      obligación y las WCAG concretan buena parte de los requisitos técnicos que luego hay que
      verificar.
    </p>

